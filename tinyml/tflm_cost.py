"""Real deployment cost of a .tflite on the target: flash = model bytes, RAM = TFLM arena_used_bytes.

The arena is measured, not estimated: firmware/src/probe.cc (TFLM + CMSIS-NN, built for the
Cortex-M4F) runs on Renode's Arduino Nano 33 BLE model with the candidate model loaded into flash,
and prints what AllocateTensors() actually used. Many models are measured per Renode launch.

Also generates the firmware's op resolver (model_ops.h) from a model's op list, so the firmware
registers exactly the ops the model uses."""
import re
import subprocess
import tempfile
import time
from pathlib import Path

PROBE_MODEL_ADDR = 0x00080000
PROBE_MAX_MODEL_BYTES = 0x00100000 - PROBE_MODEL_ADDR  # rest of the 1 MB flash
REPO = Path(__file__).resolve().parents[1]
PROBE_ELF = REPO / "firmware" / "out" / "probe_nano33ble.elf"
RENODE_CANDIDATES = [r"C:\Program Files\Renode\renode.exe", "/usr/bin/renode", "renode"]
REPL = "platforms/boards/arduino_nano_33_ble.repl"
UART = "sysbus.uart0"

# TFLite builtin name -> (MicroMutableOpResolver call, kernel header or None).
# Int8-only registrations where TFLM has them: the generic ones keep float/int16 code linked in.
OP_REGISTRATIONS = {
    "ADD": ("AddAdd(tflite::Register_ADD_INT8())", "tensorflow/lite/micro/kernels/add.h"),
    "CONCATENATION": ("AddConcatenation()", None),
    "CONV_2D": ("AddConv2D(tflite::Register_CONV_2D_INT8())", "tensorflow/lite/micro/kernels/conv.h"),
    "DEPTHWISE_CONV_2D": ("AddDepthwiseConv2D(tflite::Register_DEPTHWISE_CONV_2D_INT8())",
                          "tensorflow/lite/micro/kernels/depthwise_conv.h"),
    "FULLY_CONNECTED": ("AddFullyConnected(tflite::Register_FULLY_CONNECTED_INT8())",
                        "tensorflow/lite/micro/kernels/fully_connected.h"),
    "MEAN": ("AddMean()", None),
    "PAD": ("AddPad(tflite::Register_PAD_INT8())", "tensorflow/lite/micro/kernels/pad.h"),
    "SLICE": ("AddSlice()", None),
    "SOFTMAX": ("AddSoftmax(tflite::Register_SOFTMAX_INT8())", "tensorflow/lite/micro/kernels/softmax.h"),
    "STRIDED_SLICE": ("AddStridedSlice()", None),
}


def resolver_header(ops):
    """C++ header defining ModelOpResolver + RegisterModelOps() for exactly `ops` (TFLite builtin names)."""
    ops = sorted(set(ops))
    unknown = [o for o in ops if o not in OP_REGISTRATIONS]
    if unknown:
        raise ValueError(f"no firmware registration for ops {unknown}; add them to OP_REGISTRATIONS")
    headers = sorted({OP_REGISTRATIONS[o][1] for o in ops if OP_REGISTRATIONS[o][1]})
    lines = ["// Generated by tinyml/tflm_cost.py from the model's op list. Do not edit.",
             "#ifndef MODEL_OPS_H_", "#define MODEL_OPS_H_", ""]
    lines += [f'#include "{h}"' for h in headers]
    lines += ['#include "tensorflow/lite/micro/micro_mutable_op_resolver.h"', "",
              f"// Ops: {', '.join(ops)}",
              f"using ModelOpResolver = tflite::MicroMutableOpResolver<{len(ops)}>;", "",
              "inline TfLiteStatus RegisterModelOps(ModelOpResolver& r) {"]
    lines += [f"  TF_LITE_ENSURE_STATUS(r.{OP_REGISTRATIONS[o][0]});" for o in ops]
    lines += ["  return kTfLiteOk;", "}", "", "#endif  // MODEL_OPS_H_", ""]
    return "\n".join(lines)


def find_renode():
    import shutil
    for c in RENODE_CANDIDATES:
        if Path(c).exists() or shutil.which(c):
            return c
    raise FileNotFoundError("renode not found")


def _p(path):
    return str(Path(path).resolve()).replace("\\", "/")


def probe_script(probe_elf, jobs, run_for="00:00:01"):
    """Renode script: one machine per (model_bin, log) job, run them all for `run_for` of virtual time, quit."""
    lines = ["using sysbus"]
    for i, (model_bin, log) in enumerate(jobs):
        lines += [f'mach create "probe{i}"',
                  f"machine LoadPlatformDescription @{REPL}",
                  f"sysbus LoadELF @{_p(probe_elf)}",
                  f"sysbus LoadBinary @{_p(model_bin)} {PROBE_MODEL_ADDR:#x}",
                  f"{UART} CreateFileBackend @{_p(log)} true"]
    lines += [f'emulation RunFor "{run_for}"', "quit", ""]
    return "\n".join(lines)


PROBE_RE = re.compile(r"PROBE ok=(\d)(?: arena=(\d+) persistent=(\d+))?(?: reason=(\w+))?")


def parse_probe(text):
    """Parse the probe's console line into a dict; ok=False with a reason when it failed or never printed."""
    m = PROBE_RE.search(text or "")
    if not m:
        return {"ok": False, "reason": "no_output"}
    if m.group(1) != "1":
        return {"ok": False, "reason": m.group(4) or "unknown"}
    return {"ok": True, "arena": int(m.group(2)), "persistent": int(m.group(3))}


def measure(models, probe_elf=PROBE_ELF, batch=24, run_for="00:00:01", timeout=600, log=print,
            runner=None):
    """Measure a list of .tflite byte strings on the emulated target. Returns one dict per model:
    {ok, arena, persistent, flash} (flash = model bytes). `runner(cmd, timeout)` is injectable for tests."""
    runner = runner or (lambda cmd, t: subprocess.run(cmd, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                                                       stderr=subprocess.DEVNULL, timeout=t))
    if not Path(probe_elf).exists():
        raise FileNotFoundError(f"{probe_elf} missing: build it with `make probe` in firmware/ (WSL)")
    results, t0 = [], time.time()
    for start in range(0, len(models), batch):
        chunk = models[start:start + batch]
        with tempfile.TemporaryDirectory(prefix="tflm_probe_") as tmp:
            jobs = []
            for i, m in enumerate(chunk):
                if len(m) > PROBE_MAX_MODEL_BYTES:
                    raise ValueError(f"model {start + i} is {len(m)} B, probe flash window is {PROBE_MAX_MODEL_BYTES} B")
                mb, lg = Path(tmp, f"m{i}.bin"), Path(tmp, f"m{i}.log")
                mb.write_bytes(m)
                jobs.append((mb, lg))
            script = Path(tmp, "probe.resc")
            script.write_text(probe_script(probe_elf, jobs, run_for))
            runner([find_renode(), "--disable-gui", "--console", "--hide-log", "-e", f"include @{_p(script)}"],
                   timeout)
            for (mb, lg), m in zip(jobs, chunk):
                r = parse_probe(lg.read_text(errors="replace") if lg.exists() else "")
                r["flash"] = len(m)
                results.append(r)
        done = len(results)
        el = time.time() - t0
        log(f"[tflm probe] {done}/{len(models)} ({100 * done / len(models):.0f}%) - elapsed {el:.0f}s, "
            f"eta {el / done * (len(models) - done):.0f}s")
    return results


# ---------------------------------------------------------------- search-time cost of a spec
def spec_key(spec, patch=None):
    """Canonical key: everything in a spec that changes the deployed graph."""
    import json
    blocks = [[b["cin"], b["hidden"], b["cout"], b["k"], b["stride"]] for b in spec["blocks"]]
    return json.dumps([spec.get("pad", "torch"), spec["stem"], blocks, spec["head"], spec["num_classes"],
                       spec["res"], list(patch) if patch else None])


def lower_bounds(spec):
    """Cheap bounds the real cost can never beat: flash >= int8 weights + int32 biases; arena >= 8 B
    (int32 output multiplier + shift) per output channel of every conv, which TFLM keeps persistently."""
    from .ofa import spec_cost
    conv_channels = spec["stem"] + spec["head"] + sum(2 * b["hidden"] + b["cout"] for b in spec["blocks"])
    return {"flash": spec_cost(spec)["flash_bytes"], "arena": 8 * conv_channels}


def patch_options(spec):
    """Deployments tried per spec: plain, and 2 stripes over everything up to and including the first
    stride-2 block after the stem (the high-resolution part, where patching can lower the peak)."""
    for i, b in enumerate(spec["blocks"]):
        if b["stride"] > 1:
            return [None, (i + 2, 2)] if spec.get("pad") == "tf" else [None]
    return [None]


def _quiet_worker():
    import os
    import sys
    os.environ["TF_CPP_MIN_LOG_LEVEL"] = "3"
    devnull = os.open(os.devnull, os.O_WRONLY)
    os.dup2(devnull, 1)
    os.dup2(devnull, 2)
    sys.stdout = sys.stderr = open(os.devnull, "w")


def _convert_job(job):
    """Pool worker: random-weight model for (spec, patch) -> stripped int8 .tflite bytes."""
    spec, patch, seed = job
    import numpy as np

    from .tfl_build import build_keras, convert, ir_from_spec, strip_names
    calib = np.random.default_rng(seed).integers(0, 256, (8, 3, spec["res"], spec["res"]), dtype=np.uint8)
    return strip_names(convert(build_keras(ir_from_spec(spec, seed), patch=patch), calib, n_calib=8))


class RealCost:
    """Measured (flash, arena) per spec, best over patch_options(spec), with an append-only JSONL cache
    so an interrupted search resumes without re-measuring. Conversions run in a process pool (TF only,
    no torch in the workers); the converted models are then measured in batches on Renode."""

    def __init__(self, cache_path, flash_limit, ram_limit, workers=12, probe_elf=PROBE_ELF, log=print,
                 convert_fn=None, measure_fn=None, patch_margin=1.3):
        import json
        self.cache_path, self.flash_limit, self.ram_limit = Path(cache_path), flash_limit, ram_limit
        self.patch_margin = patch_margin
        self.workers, self.probe_elf, self.log = workers, probe_elf, log
        self.convert_fn, self.measure_fn = convert_fn, measure_fn or measure
        self.cache, self._pool = {}, None
        if self.cache_path.exists():
            for line in self.cache_path.read_text().splitlines():
                if line.strip():
                    rec = json.loads(line)
                    self.cache[rec["key"]] = rec["result"]
            self.log(f"[real cost] resumed {len(self.cache)} cached measurements from {self.cache_path}")

    def _convert_all(self, jobs):
        if self.convert_fn:
            return [self.convert_fn(j) for j in jobs]
        if self._pool is None:
            import multiprocessing as mp
            self._pool = mp.get_context("spawn").Pool(self.workers, initializer=_quiet_worker)
        out, t0 = [None] * len(jobs), time.time()
        step = max(1, len(jobs) // 10)
        for n, (i, b) in enumerate(self._pool.imap_unordered(_indexed_convert, list(enumerate(jobs))), 1):
            out[i] = b
            if n % step == 0 or n == len(jobs):
                el = time.time() - t0
                self.log(f"[real cost] converted {n}/{len(jobs)} ({100 * n / len(jobs):.0f}%) "
                         f"- elapsed {el:.0f}s, eta {el / n * (len(jobs) - n):.0f}s")
        return out

    def _within(self, r):
        return bool(r and r.get("ok") and r["flash"] <= self.flash_limit and r["arena"] <= self.ram_limit)

    def _measure(self, pairs):
        import json
        todo, seen = [], set()
        for s, p in pairs:
            k = spec_key(s, p)
            if k not in self.cache and k not in seen:
                seen.add(k)
                todo.append((k, s, p))
        if not todo:
            return
        models = self._convert_all([(s, p, 0) for _, s, p in todo])
        results = self.measure_fn(models, self.probe_elf, log=self.log)
        with open(self.cache_path, "a") as f:
            for (k, _, p), r in zip(todo, results):
                r = dict(r, patch=list(p) if p else None)
                self.cache[k] = r
                f.write(json.dumps({"key": k, "result": r}) + "\n")

    def measure_specs(self, specs, all_options=False):
        """Measure the plain deployment of every spec; patched deployments only where the plain one
        misses the budget by at most `patch_margin` (patching never saved more than that in practice:
        it duplicates per-op persistent data per stripe), or for every spec with all_options=True."""
        self._measure([(s, None) for s in specs])
        second = []
        for s in specs:
            r = self.cache[spec_key(s, None)]
            near = r.get("ok") and not self._within(r) and r["arena"] <= self.patch_margin * self.ram_limit
            if all_options or near:
                second += [(s, p) for p in patch_options(s)[1:]]
        self._measure(second)

    def cost(self, spec, all_options=False):
        """Best measured deployment of spec: within budget first, then smallest arena (None if nothing
        allocates). Only options measured so far are considered (see measure_specs)."""
        self.measure_specs([spec], all_options)
        opts = [self.cache.get(spec_key(spec, p)) for p in patch_options(spec)]
        opts = [o for o in opts if o and o.get("ok")]
        return min(opts, key=lambda o: (not self._within(o), o["arena"], o["flash"])) if opts else None

    def fits_many(self, specs):
        """Feasibility for a batch: lower bounds prune first, survivors are measured together."""
        ok_lb = [lower_bounds(s)["flash"] <= self.flash_limit and lower_bounds(s)["arena"] <= self.ram_limit
                 for s in specs]
        self.measure_specs([s for s, ok in zip(specs, ok_lb) if ok])
        return [ok and self._within(self.cost(s)) for s, ok in zip(specs, ok_lb)]

    def close(self):
        if self._pool is not None:
            self._pool.close()
            self._pool.join()
            self._pool = None


def _indexed_convert(item):
    i, job = item
    return i, _convert_job(job)
